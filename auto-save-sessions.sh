#!/bin/bash
# auto-save-sessions.sh — Cron job that captures live git state for active projects.
#
# Concurrency-safe model (redesigned 2026-06-30):
#
#   SESSION_STATUS.md   <- this script OWNS it. Gitignored via .git/info/exclude.
#                          Live git-derived status (branch, changed files, recent
#                          commits, timestamp). Overwritten whole each tick. Never
#                          committed, per-working-tree, so it can never clobber human
#                          content or collide between concurrent sessions/worktrees.
#
#   SESSION_STATE.md    <- humans/Claude OWN it. A thin, durable, COMMITTED index
#                          (Current Focus, Active Workstreams table, etc.). This script
#                          NEVER writes it, except a one-shot legacy cleanup: if it still
#                          carries the old AUTO-GEN block, the block is replaced once with
#                          a pointer line, then the file is never touched again.
#
#   docs/notes/<branch>.md <- per-stream working detail, committed on each branch.
#
# Why the change: the old script rewrote an AUTO-GEN block INSIDE the committed
# SESSION_STATE.md as uncommitted edits. With concurrent sessions (e.g. a worktree +
# a live main checkout) those edits were stranded in one tree and raced the cron and
# other sessions. Moving live status to a gitignored sidecar removes the cron as a
# writer to any shared/committed file, which dissolves the contention entirely.
#
# ─────────────────────────────────────────────────────────────────────────────
# RETIRED 2026-07-01 (Chris): the 10-minute auto-save is turned off. It rewrote a
# SESSION_STATUS.md in every repo with uncommitted files each tick, bumping folder
# mtimes across the Mac mini — pure noise, since SESSION_STATUS.md is only a
# regenerable cache of `git status` / `git log`. Live git state is now read on
# demand at resume time instead. The crontab entry is being removed; this guard
# makes any lingering tick a no-op. To re-enable, delete the two lines below.
echo "[$(date '+%Y-%m-%d %H:%M:%S')] session auto-save is RETIRED (2026-07-01) — no-op, exiting."
exit 0
# ─────────────────────────────────────────────────────────────────────────────

set -u

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

CONFIG_FILE="${SESSION_CONTINUITY_CONFIG:-$SCRIPT_DIR/config}"
if [ ! -f "$CONFIG_FILE" ]; then
    echo "ERROR: Config file not found: $CONFIG_FILE"
    echo "Run ./install.sh or copy config.example to config and edit it."
    exit 1
fi
# shellcheck disable=SC1090
source "$CONFIG_FILE"

ACTIVITY_WINDOW="${ACTIVITY_WINDOW:-30}"
SKIP_DIRS="${SKIP_DIRS:-}"

STATUS_FILE_NAME="SESSION_STATUS.md"

# Legacy markers — only used to detect + retire the old in-SESSION_STATE auto block.
MARKER_START="<!-- AUTO-GEN-START — managed by session-continuity cron, do not edit -->"
MARKER_END="<!-- AUTO-GEN-END -->"
LEGACY_POINTER="> Live git status (auto): see ${STATUS_FILE_NAME} (gitignored). This file is now a durable, committed index — edit on your branch and commit."

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $1"
}

# Build the full SESSION_STATUS.md body for a project's current git state.
# Args: branch, last_commit, last_commit_time, changed_files, recent_commits
build_status() {
    local branch="$1" last_commit="$2" last_commit_time="$3" changed="$4" recent="$5"
    cat <<EOF
# Session Status — auto-saved (do not edit; gitignored)

_Generated by session-continuity cron. The durable, human-owned index is SESSION_STATE.md._

**Branch:** $branch
**Last commit:** $last_commit
**Last commit time:** $last_commit_time

## Files Changed
$changed

## Recent Commits
$recent

_Auto-saved: $(date '+%Y-%m-%d %H:%M:%S')_
EOF
}

# Atomically write $2 as the entire contents of file $1 (tmp + mv).
write_file_atomic() {
    local file="$1" content="$2"
    local tmp="${file}.tmp.$$"
    printf '%s\n' "$content" > "$tmp" || { rm -f "$tmp"; return 1; }
    [ -s "$tmp" ] || { rm -f "$tmp"; return 1; }
    mv "$tmp" "$file"
}

# Ensure SESSION_STATUS.md is excluded locally via .git/info/exclude.
# Per-repo, never committed — keeps the cron from ever dirtying a tracked file.
ensure_local_exclude() {
    local gitdir
    gitdir=$(git rev-parse --git-dir 2>/dev/null) || return 0
    mkdir -p "$gitdir/info" 2>/dev/null
    local exclude="$gitdir/info/exclude"
    if [ ! -f "$exclude" ] || ! grep -qxF "$STATUS_FILE_NAME" "$exclude" 2>/dev/null; then
        printf '%s\n' "$STATUS_FILE_NAME" >> "$exclude"
    fi
}

# One-shot legacy cleanup: if SESSION_STATE.md still has the old AUTO-GEN block,
# replace the marker-bounded block (inclusive) with a single pointer line. Only
# touches content between the markers; all human sections are preserved. Atomic +
# sanity-checked. After this runs once, the markers are gone and we never touch it again.
retire_legacy_block() {
    local file="$1"
    [ -f "$file" ] || return 0
    grep -qF "$MARKER_START" "$file" || return 0   # nothing to do

    local tmp="${file}.tmp.$$"
    awk -v start="$MARKER_START" -v end="$MARKER_END" -v pointer="$LEGACY_POINTER" '
        BEGIN { inblock = 0; done = 0 }
        $0 == start { inblock = 1; if (!done) { print pointer; done = 1 } next }
        $0 == end   { inblock = 0; next }
        !inblock    { print }
    ' "$file" > "$tmp"
    local rc=$?

    # Sanity: succeeded, non-empty, and markers actually gone.
    if [ $rc -ne 0 ] || [ ! -s "$tmp" ] || grep -qF "$MARKER_START" "$tmp" || grep -qF "$MARKER_END" "$tmp"; then
        rm -f "$tmp"
        log "  -> WARN: legacy SESSION_STATE cleanup failed; leaving file untouched."
        return 1
    fi
    mv "$tmp" "$file"
    log "  -> Retired legacy AUTO-GEN block in SESSION_STATE.md (one-shot)."
}

for project_dir in "$PROJECTS_DIR"/*/; do
    project_name=$(basename "$project_dir")

    if echo "$SKIP_DIRS" | grep -qw "$project_name"; then
        continue
    fi

    if [ ! -d "$project_dir/.git" ]; then
        continue
    fi

    # Only manage projects that have opted into session-continuity (have a SESSION_STATE.md).
    state_file="$project_dir/SESSION_STATE.md"
    if [ ! -f "$state_file" ]; then
        continue
    fi

    status_file="$project_dir/$STATUS_FILE_NAME"

    cd "$project_dir" || continue

    # Refresh when there's git activity OR the sidecar is missing/stale relative to the tree.
    recent_changes=$(find . -not -path './.git/*' -not -name "$STATUS_FILE_NAME" -newer "$status_file" -type f 2>/dev/null | head -1)
    has_uncommitted=$(git status --porcelain 2>/dev/null | head -1)

    if [ -f "$status_file" ] && [ -z "$recent_changes" ] && [ -z "$has_uncommitted" ]; then
        continue
    fi

    log "Updating: $project_name"

    ensure_local_exclude
    retire_legacy_block "$state_file"

    branch=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "unknown")
    last_commit=$(git log --oneline -1 2>/dev/null || echo "no commits")
    last_commit_time=$(git log -1 --format='%ci' 2>/dev/null || echo "unknown")

    unstaged=$(git diff --name-only 2>/dev/null)
    staged=$(git diff --cached --name-only 2>/dev/null)
    untracked=$(git ls-files --others --exclude-standard 2>/dev/null)

    changed_files=""
    if [ -n "$unstaged" ]; then
        changed_files="$changed_files
**Modified (unstaged):**
$(echo "$unstaged" | sed 's/^/- /')"
    fi
    if [ -n "$staged" ]; then
        changed_files="$changed_files
**Staged:**
$(echo "$staged" | sed 's/^/- /')"
    fi
    if [ -n "$untracked" ]; then
        changed_files="$changed_files
**Untracked:**
$(echo "$untracked" | head -10 | sed 's/^/- /')"
    fi
    if [ -z "$changed_files" ]; then
        changed_files="- (working tree clean)"
    fi

    recent_commits=$(git log --oneline -5 2>/dev/null | sed 's/^/- /')

    status_body=$(build_status "$branch" "$last_commit" "$last_commit_time" "$changed_files" "$recent_commits")

    if write_file_atomic "$status_file" "$status_body"; then
        log "  -> Branch: $branch | Files: $(echo "$unstaged $staged $untracked" | wc -w | tr -d ' ') | wrote $STATUS_FILE_NAME"
    else
        log "  -> WARN: failed to write $STATUS_FILE_NAME for $project_name. Skipping."
    fi
done

log "Session auto-save complete."
